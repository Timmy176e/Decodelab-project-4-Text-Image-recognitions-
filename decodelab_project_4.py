import cv2

# blur to remove scanner noise/grain before thresholding
blurred = cv2.GaussianBlur(img, (5, 5), 0)

# Otsu's method: automatically finds the best cutoff instead of a fixed number like 88
_, thresh = cv2.threshold(blurred, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)

fig, axes = plt.subplots(1, 3, figsize=(15, 5))
axes[0].imshow(img, cmap='gray'); axes[0].set_title('Original'); axes[0].axis('off')
axes[1].imshow(blurred, cmap='gray'); axes[1].set_title('Blurred'); axes[1].axis('off')
axes[2].imshow(thresh, cmap='gray'); axes[2].set_title('Otsu Threshold'); axes[2].axis('off')
plt.show()

adaptive = cv2.adaptiveThreshold(
    blurred, 255,
    cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
    cv2.THRESH_BINARY,
    blockSize=25,   # size of the local neighborhood it examines
    C=10            # constant subtracted from the local mean — tune if too noisy/sparse
)

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
axes[0].imshow(thresh, cmap='gray'); axes[0].set_title('Otsu (global)'); axes[0].axis('off')
axes[1].imshow(adaptive, cmap='gray'); axes[1].set_title('Adaptive (local)'); axes[1].axis('off')
plt.show()

import numpy as np

# artificially tilt the clean image to simulate a crooked scan
(h, w) = adaptive.shape
M_tilt = cv2.getRotationMatrix2D((w // 2, h // 2), 8, 1.0)  # 8-degree tilt
tilted = cv2.warpAffine(adaptive, M_tilt, (w, h), borderValue=255)

# --- deskew: find the angle, then rotate it back ---
coords = np.column_stack(np.where(tilted < 255))  # locations of dark (text) pixels
angle = cv2.minAreaRect(coords)[-1]
if angle < -45:
    angle = -(90 + angle)
else:
    angle = -angle

M_fix = cv2.getRotationMatrix2D((w // 2, h // 2), angle, 1.0)
deskewed = cv2.warpAffine(tilted, M_fix, (w, h), borderValue=255)

fig, axes = plt.subplots(1, 3, figsize=(15, 5))
axes[0].imshow(adaptive, cmap='gray'); axes[0].set_title('Clean (adaptive)'); axes[0].axis('off')
axes[1].imshow(tilted, cmap='gray'); axes[1].set_title('Artificially Tilted'); axes[1].axis('off')
axes[2].imshow(deskewed, cmap='gray'); axes[2].set_title(f'Deskewed ({angle:.1f}°)'); axes[2].axis('off')
plt.show()

# pytesseract needs a normal image, not inverted binary — and works best on the clean image
data = pytesseract.image_to_data(adaptive, output_type=pytesseract.Output.DICT)

CONFIDENCE_THRESHOLD = 80
accepted_words = []

for i in range(len(data['text'])):
    word = data['text'][i].strip()
    conf = int(data['conf'][i])
    if word and conf >= CONFIDENCE_THRESHOLD:
        accepted_words.append((word, conf))

print("--- Accepted words (confidence >= 80%) ---")
for word, conf in accepted_words:
    print(f"{word!r}  ({conf}%)")

print("\n--- Final extracted text ---")
print(" ".join(w for w, c in accepted_words))

boxed = cv2.cvtColor(adaptive, cv2.COLOR_GRAY2BGR)

for i in range(len(data['text'])):
    word = data['text'][i].strip()
    conf = int(data['conf'][i])
    if word and conf >= CONFIDENCE_THRESHOLD:
        x, y, w, h = data['left'][i], data['top'][i], data['width'][i], data['height'][i]
        cv2.rectangle(boxed, (x, y), (x + w, y + h), (0, 255, 0), 1)

plt.figure(figsize=(10, 6))
plt.imshow(cv2.cvtColor(boxed, cv2.COLOR_BGR2RGB))
plt.title(f'Accepted words boxed (confidence >= {CONFIDENCE_THRESHOLD}%)')
plt.axis('off')
plt.show()

